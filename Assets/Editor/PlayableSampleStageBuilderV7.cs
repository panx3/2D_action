    private static void SpawnEnemy(Transform parent, GameObject prefab, string name, Vector2 position, float _)
    {
        GameObject enemy = Spawn(prefab, parent, name, position);

        Sprite enemySprite = LoadFirstSprite(EnemySpritePath);
        SpriteRenderer renderer = enemy.GetComponent<SpriteRenderer>();
        BoxCollider2D collider = enemy.GetComponent<BoxCollider2D>();

        float desiredHeight = Mathf.Clamp(metrics.height * 0.56f, 1.25f, 1.90f);
        float spriteScale = desiredHeight / Mathf.Max(0.0001f, enemySprite != null ? enemySprite.bounds.size.y : 1f);
        enemy.transform.localScale = new Vector3(spriteScale, spriteScale, 1f);

