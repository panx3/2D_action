    private static void LinkUnityEvent(Component owner, string fieldName, UnityAction action)
    {
        if (owner == null)
            return;

        FieldInfo field = owner.GetType().GetField(fieldName, BindingFlags.Instance | BindingFlags.NonPublic);
        if (field == null || !typeof(UnityEvent).IsAssignableFrom(field.FieldType))
        {
            Debug.LogWarning(owner.GetType().Name + "." + fieldName + " was not found.", owner);
            return;
        }

        UnityEvent unityEvent = field.GetValue(owner) as UnityEvent;
        if (unityEvent == null)
        {
            unityEvent = new UnityEvent();
            field.SetValue(owner, unityEvent);
        }

        while (unityEvent.GetPersistentEventCount() > 0)
            UnityEventTools.RemovePersistentListener(unityEvent, 0);

        UnityEventTools.AddPersistentListener(unityEvent, action);
        EditorUtility.SetDirty(owner);
    }

