    private static void BuildGimmicks(
        Transform root,
        StageAssets assets,
        GimmickRespawnController respawn,
        DeathRespawnManager deathRespawn,
        Transform morningStar)
    {
        Sprite boxSprite = LoadFirstSprite(BoxPath);
