    private static void SetSerialized(UnityEngine.Object target, string fieldName, Action<SerializedProperty> write)
    {
        if (target == null)
            return;

        SerializedObject serialized = new SerializedObject(target);
        SerializedProperty property = serialized.FindProperty(fieldName);
        if (property == null)
        {
            Debug.LogWarning(target.GetType().Name + "." + fieldName + " was not found.", target);
            return;
        }

        write(property);
        serialized.ApplyModifiedPropertiesWithoutUndo();
        EditorUtility.SetDirty(target);
    }

    private static float ReadPrivateFloat(UnityEngine.Object target, string fieldName, float fallback)
    {
        if (target == null)
            return fallback;

        SerializedObject serialized = new SerializedObject(target);
        SerializedProperty property = serialized.FindProperty(fieldName);
        return property != null ? property.floatValue : fallback;
    }

