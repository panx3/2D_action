    private static bool TryReadPlayerMetrics(Player player, out PlayerMetrics result)
    {
        result = default;

        CapsuleCollider2D capsule = player.GetComponent<CapsuleCollider2D>();
        Rigidbody2D rb = player.GetComponent<Rigidbody2D>();
        if (capsule == null || rb == null)
            return false;

        float sx = Mathf.Abs(player.transform.lossyScale.x);
        float sy = Mathf.Abs(player.transform.lossyScale.y);

        result.width = capsule.size.x * sx;
        result.height = capsule.size.y * sy;
        result.footOffsetFromRoot = (capsule.offset.y - capsule.size.y * 0.5f) * sy;
        result.topOffsetFromRoot = (capsule.offset.y + capsule.size.y * 0.5f) * sy;
        result.rootYOnGround = GroundTop - result.footOffsetFromRoot + 0.06f;

        float jumpImpulse = ReadPrivateFloat(player, "_jumpSpeed", 7f);
        float gravity = Mathf.Abs(Physics2D.gravity.y) * Mathf.Max(0.01f, rb.gravityScale);
        float theoreticalJumpHeight = jumpImpulse * jumpImpulse / (2f * gravity);

        // 頭がぶつからず、慣性や入力ミスがあっても渡りやすい安全値。
        result.safeStepHeight = Mathf.Clamp(theoreticalJumpHeight * 0.32f, result.height * 0.18f, result.height * 0.30f);
        result.safePlatformWidth = Mathf.Max(result.width * 4.8f, 4.8f);
        result.guideCharacterSize = Mathf.Clamp(result.height * 0.060f, 0.16f, 0.22f);
        result.gateHeight = Mathf.Max(result.height * 1.05f, theoreticalJumpHeight * 1.20f);

        return result.width > 0.01f && result.height > 0.01f;
    }

