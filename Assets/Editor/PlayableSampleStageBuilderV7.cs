    [MenuItem("鉄球少女/SampleScene/ギミック強化ステージを生成（v7）")]
    private static void BuildStage()
    {
        if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            return;

        Player player = UnityEngine.Object.FindAnyObjectByType<Player>(FindObjectsInactive.Exclude);
        if (player == null)
        {
            EditorUtility.DisplayDialog("Playerが見つかりません", "SampleScene内にPlayerを配置してから実行してください。", "OK");
            return;
        }

        if (!TryReadPlayerMetrics(player, out metrics))
        {
            EditorUtility.DisplayDialog("Player設定を読み取れません", "PlayerにCapsuleCollider2DとRigidbody2Dが必要です。", "OK");
            return;
        }

        if (!TryLoadAssets(out StageAssets assets) || !EnsureTiles())
            return;

        terrainLayer = LayerMask.NameToLayer(WallTag);
        if (terrainLayer < 0)
            terrainLayer = 0;

        RemoveRoot(RootName);
        RemoveRoot(OldRootName);
        RemoveRoot(LegacyRootName);
        DisableLegacyObjects();

        GameObject rootObject = new GameObject(RootName);
        Undo.RegisterCreatedObjectUndo(rootObject, "Generate playable stage v7");

        Transform geometryRoot = CreateGroup(rootObject.transform, "01_Geometry");
        Transform visualRoot = CreateGroup(rootObject.transform, "02_Visuals");
        Transform gimmickRoot = CreateGroup(rootObject.transform, "03_Gimmicks");
        Transform enemyRoot = CreateGroup(rootObject.transform, "04_Enemies");
        Transform guideRoot = CreateGroup(rootObject.transform, "05_Guides");
        Transform systemRoot = CreateGroup(rootObject.transform, "06_Systems");

        SetupPlayer(player, systemRoot, out Transform morningStar, out GimmickRespawnController respawn, out DeathRespawnManager deathRespawn);

        TerrainRects.Clear();
        BuildGeometry(geometryRoot);
        BuildTileVisuals(visualRoot);
        BuildHazards(gimmickRoot, assets, respawn);
        BuildGimmicks(gimmickRoot, assets, respawn, deathRespawn, morningStar);
        BuildEnemies(enemyRoot, assets);
        BuildGuides(guideRoot);
        ConfigureCameraBounds();

        Debug.Log(
            "[Stage v7] Player基準でギミック強化ステージを生成しました。"
            + $" Collider={metrics.width:F2} x {metrics.height:F2},"
            + $" 立ち位置Y={metrics.rootYOnGround:F2},"
            + $" 安全段差={metrics.safeStepHeight:F2},"
            + $" 推奨足場幅={metrics.safePlatformWidth:F2}");

        EditorSceneManager.MarkSceneDirty(SceneManager.GetActiveScene());
        Selection.activeGameObject = rootObject;
        SceneView.lastActiveSceneView?.FrameSelected();

        EditorUtility.DisplayDialog(
            "v7生成完了",
            "PlayerのCapsuleCollider2DとRigidbody2Dを読み取って生成しました。\n\n"
            + "・開始地点のめり込み補正\n"
            + "・動く床 / 落ちる床 / 磁力に落下リスクを追加\n"
            + "・磁力区画は下に地面がない必須ルート\n"
            + "・壊せる木箱の破片も木箱に統一\n"
            + "・文字はPlayerの高さ基準で大きく表示\n\n"
            + "保存してPlayで確認してください。",
            "OK");
    }

