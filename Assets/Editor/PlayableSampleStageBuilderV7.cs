    private static void SetupPlayer(
        Player player,
        Transform systemRoot,
        out Transform morningStar,
        out GimmickRespawnController respawn,
        out DeathRespawnManager deathRespawn)
    {
        Vector3 spawn = new Vector3(2.5f, metrics.rootYOnGround, 0f);
        player.transform.position = spawn;

        Rigidbody2D playerRb = player.GetComponent<Rigidbody2D>();
        if (playerRb != null)
        {
            playerRb.linearVelocity = Vector2.zero;
            playerRb.angularVelocity = 0f;
        }

        GameObject ball = FindGameObjectWithTagSafely("morningstar");
        morningStar = ball != null ? ball.transform : null;
        if (morningStar != null)
        {
            morningStar.position = spawn + new Vector3(-metrics.width * 1.45f, 0f, 0f);
            Rigidbody2D ballRb = morningStar.GetComponent<Rigidbody2D>();
            if (ballRb != null)
            {
                ballRb.linearVelocity = Vector2.zero;
                ballRb.angularVelocity = 0f;
            }
        }

        GameObject spawnObject = new GameObject("InitialSpawn");
        spawnObject.transform.SetParent(systemRoot);
        spawnObject.transform.position = spawn;

        deathRespawn = UnityEngine.Object.FindAnyObjectByType<DeathRespawnManager>(FindObjectsInactive.Exclude);
        if (deathRespawn != null)
        {
            SetObjectReference(deathRespawn, "_defaultSpawnPoint", spawnObject.transform);
            SetObjectReference(deathRespawn, "_player", player);
            SetObjectReference(deathRespawn, "_playerHealth", player.GetComponent<PlayerHealth>());
        }

        GameObject respawnObject = new GameObject("GimmickRespawnController");
        respawnObject.transform.SetParent(systemRoot);
        respawn = respawnObject.AddComponent<GimmickRespawnController>();
        SetObjectReference(respawn, "player", player.transform);
        SetObjectReference(respawn, "playerRigidbody", playerRb);
        SetObjectReference(respawn, "initialRespawnPoint", spawnObject.transform);
        SetObjectReference(respawn, "morningstar", morningStar);
        SetObjectReference(respawn, "morningstarRigidbody", morningStar != null ? morningStar.GetComponent<Rigidbody2D>() : null);
        SetVector2(respawn, "morningstarOffset", new Vector2(-metrics.width * 1.45f, 0f));
    }

