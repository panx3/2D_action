    private static void BuildGeometry(Transform root)
    {
        float step = metrics.safeStepHeight;
        float platform = metrics.safePlatformWidth;
        float gateHeight = metrics.gateHeight;
        float roofCenterY = gateHeight + metrics.height * 0.48f;
        const float roofHeight = 0.45f;

        // 1. 開始区画。ここだけは安全地帯として、操作の確認を行う。
        CreateFloor(root, "StartGround", -8f, 14.0f, GroundTop);
        CreateFloor(root, "StartPracticeStep", 7.1f, 7.1f + platform, step);

        // 2. 木箱を壊し、スイッチでドアを開く区画。
        CreateFloor(root, "BreakAndSwitchGround", 14.0f, 29.0f, GroundTop);
        CreateWall(root, "BreakRouteRoof", 14.7f, 25.4f, roofCenterY, roofHeight);

        // 3. 動く床の穴。床を待つか、上のビームに鉄球を当てて補助できる。
        CreateFloor(root, "MovingLeftBank", 29.0f, 32.0f, GroundTop);
        CreateFloor(root, "MovingRightBank", 38.2f, 46.0f, GroundTop);
        CreateWall(root, "MovingPracticeBeam", 33.1f, 37.2f, roofCenterY + 0.85f, roofHeight);

        // 4. 落ちる床の穴。落下前に右岸へ移動する。
        CreateFloor(root, "FallingLeftBank", 46.0f, 48.0f, GroundTop);
        CreateFloor(root, "FallingRightBank", 53.2f, 61.0f, GroundTop);

        // 5. 重量スイッチ。鉄球をプレートに残してドアを開ける。
        CreateFloor(root, "WeightGround", 61.0f, 74.6f, GroundTop);
        CreateWall(root, "WeightRouteRoof", 66.0f, 72.8f, roofCenterY, roofHeight);

        // 6. 磁力峡谷。下に地面はなく、2つの磁力点を使って渡る必須区画。
        //    左の発射台 -> 中継浮島 -> ゴール島。通常ジャンプだけでは届かない間隔にしている。
        CreateFloor(root, "MagnetLaunchLedge", 74.6f, 76.8f, step * 0.72f);
        CreateFloor(root, "MagnetRestIsland", 81.4f, 82.8f, step * 1.05f);
        CreateFloor(root, "GoalIsland", 87.0f, 99.0f, step * 0.72f);

        // ゴール奥の壁は見た目だけ。プレイヤーの進行は止めない。
        CreateWall(root, "GoalBackWall", 98.6f, 99.2f, step * 0.72f + 1.8f, 3.6f);
    }

    private static void BuildHazards(Transform root, StageAssets assets, GimmickRespawnController respawn)
    {
        // 失敗しても現在のチェックポイントへすぐ戻れるよう、危険区画の底だけにリスポーン帯を置く。
        CreateHazardBand(root, assets, respawn, "MovingGapHazard", 35.1f, 6.8f);
        CreateHazardBand(root, assets, respawn, "FallingGapHazard", 50.6f, 5.6f);
        CreateHazardBand(root, assets, respawn, "MagnetChasmHazard", 81.9f, 10.6f);
    }

    private static void CreateHazardBand(Transform parent, StageAssets assets, GimmickRespawnController respawn, string name, float centerX, float width)
    {
        GameObject spikes = Spawn(assets.spikeTrap, parent, name + "_Spikes", new Vector2(centerX, -1.15f));
        FitPrefabToWorldSize(spikes, LoadFirstSprite(SpikePath), new Vector2(width, 0.60f), Color.white);
        LinkUnityEvent(spikes.GetComponent<SpikeTrap>(), "onPlayerHit", respawn.Respawn);

        GameObject zone = Spawn(assets.respawnZone, parent, name + "_Respawn", new Vector2(centerX, -3.6f));
        SetBoxColliderWorldSize(zone, new Vector2(width + 1.0f, 2.8f));
        SetObjectReference(zone.GetComponent<RespawnZone>(), "gimmickRespawnController", respawn);
        HideBaseSprite(zone);
    }

