        float step = metrics.safeStepHeight;

        // 壊せる壁は2x2の木箱。破片も同じ木箱素材に統一する。
        GameObject woodFragmentTemplate = CreateWoodCrateFragmentTemplate(root, boxSprite);

        GameObject breakableBox = Spawn(
            assets.breakableWall,
            root,
            "BreakableCrateBarrier",
            new Vector2(16.8f, gateHeight * 0.5f));

        SetBoxColliderWorldSize(breakableBox, new Vector2(metrics.width * 2.15f, gateHeight));
        HideBaseSprite(breakableBox);
        CreateCrateStackVisual(
            breakableBox.transform,
            boxSprite,
            2,
            2,
            new Vector2(metrics.width * 1.98f, gateHeight * 0.92f));

        BreakableWall breakableWall = breakableBox.GetComponent<BreakableWall>();
        SetObjectReference(breakableWall, "fragmentPrefab", woodFragmentTemplate);
        SetInt(breakableWall, "fragmentCount", 7);
        SetFloat(breakableWall, "fragmentSpread", 0.45f);
        SetFloat(breakableWall, "minForce", 1.8f);
        SetFloat(breakableWall, "maxForce", 3.2f);

        // 壁の先で鉄球を当てるヒットスイッチ。
        GameObject hitSwitch = Spawn(assets.hitSwitch, root, "HitSwitch", new Vector2(21.0f, 0.62f));
        FitPrefabToWorldSize(hitSwitch, blockSprite, new Vector2(0.95f, 0.95f), new Color(1f, 0.50f, 0.20f, 1f));

        GameObject hitDoor = Spawn(assets.door, root, "HitDoor", new Vector2(24.3f, gateHeight * 0.5f));
        FitPrefabToWorldSize(hitDoor, blockSprite, new Vector2(metrics.width * 1.35f, gateHeight), new Color(0.95f, 0.25f, 0.24f, 1f));
        ConfigureDoorStartsOpen(hitDoor.GetComponent<GimmickDoor>(), false);
        ConfigureHitSwitch(hitSwitch.GetComponent<HitSwitch>(), hitDoor.GetComponent<GimmickDoor>());

        GameObject checkpointA = Spawn(assets.checkpoint, root, "Checkpoint_AfterDoor", new Vector2(27.5f, 0.90f));
        FitPrefabToWorldSize(checkpointA, checkpointSprite, new Vector2(1.0f, 1.55f), Color.white);
        ConfigureCheckpoint(checkpointA.GetComponent<Checkpoint>(), respawn, deathRespawn);

        // 動く床は両岸へ重なる位置を往復する。
        GameObject movingPlatform = Spawn(assets.movingPlatform, root, "MovingPlatform", new Vector2(33.9f, 0.28f));
        FitPrefabToWorldSize(movingPlatform, movingSprite, new Vector2(4.8f, 0.56f), Color.white);
        ConfigureMovingPlatform(movingPlatform.GetComponent<MovingPlatform>(), new Vector2(3.6f, 0f), 1.25f, 1.0f);

        // 落ちる床は渡り切れる時間を残すが、立ち止まると危険。
        GameObject fallingPlatform = Spawn(assets.fallingPlatform, root, "FallingPlatform", new Vector2(50.5f, 0.31f));
        FitPrefabToWorldSize(fallingPlatform, fallingSprite, new Vector2(4.4f, 0.62f), Color.white);
        ConfigureFallingPlatform(fallingPlatform.GetComponent<FallingPlatform>(), 1.35f, 3.0f);

        // 重量スイッチ。ドアは一度開けば閉じない。
        GameObject weightSwitch = Spawn(assets.weightSwitch, root, "WeightSwitch", new Vector2(64.4f, 0.24f));
        FitPrefabToWorldSize(weightSwitch, weightSprite, new Vector2(3.4f, 0.48f), new Color(0.70f, 0.90f, 1f, 1f));

        GameObject weightDoor = Spawn(assets.door, root, "WeightDoor", new Vector2(69.2f, gateHeight * 0.5f));
        FitPrefabToWorldSize(weightDoor, blockSprite, new Vector2(metrics.width * 1.35f, gateHeight), new Color(0.30f, 0.68f, 1f, 1f));
        ConfigureDoorStartsOpen(weightDoor.GetComponent<GimmickDoor>(), false);
        ConfigureWeightSwitch(weightSwitch.GetComponent<WeightSwitch>(), weightDoor.GetComponent<GimmickDoor>());

        GameObject checkpointB = Spawn(assets.checkpoint, root, "Checkpoint_BeforeMagnetChasm", new Vector2(73.3f, 0.90f));
        FitPrefabToWorldSize(checkpointB, checkpointSprite, new Vector2(1.0f, 1.55f), Color.white);
        ConfigureCheckpoint(checkpointB.GetComponent<Checkpoint>(), respawn, deathRespawn);

        // 磁力峡谷。鉄球が磁力点に入っている間、Playerにも短い磁力ダッシュを与える。
        // MagnetPoint.cs の「Traversal Assist」を有効にしている。
        GameObject magnetA = Spawn(assets.magnet, root, "MagnetPoint_A", new Vector2(79.25f, step * 0.72f + 3.10f));
        FitPrefabToWorldSize(magnetA, magnetSprite, new Vector2(1.22f, 1.22f), new Color(0.20f, 0.90f, 1f, 1f));
        ConfigureCircleColliderWorldRadius(magnetA.GetComponent<CircleCollider2D>(), magnetA.transform, 2.0f);
        ConfigureMagnetTraversal(magnetA.GetComponent<MagnetPoint>(), 68f, 13f, 0.85f);

        GameObject magnetB = Spawn(assets.magnet, root, "MagnetPoint_B", new Vector2(84.45f, step * 1.05f + 3.10f));
        FitPrefabToWorldSize(magnetB, magnetSprite, new Vector2(1.22f, 1.22f), new Color(0.20f, 0.90f, 1f, 1f));
