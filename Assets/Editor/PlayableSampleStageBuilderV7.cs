    private static bool EnsureTiles()
    {
        UnityEngine.Object[] terrainAssets = AssetDatabase.LoadAllAssetsAtPath(TerrainSheetPath);
        if (terrainAssets == null || terrainAssets.Length == 0)
        {
            EditorUtility.DisplayDialog("Terrain素材がありません", TerrainSheetPath + " が見つかりません。", "OK");
            return false;
        }

        Sprite goldTopSprite = FindSprite(terrainAssets, "Terrain (16x16)_112");
        Sprite goldFillSprite = FindSprite(terrainAssets, "Terrain (16x16)_111");
        Sprite goldAccentSprite = FindSprite(terrainAssets, "Terrain (16x16)_113");
        Sprite ruinTopSprite = FindSprite(terrainAssets, "Terrain (16x16)_106");
        Sprite ruinFillSprite = FindSprite(terrainAssets, "Terrain (16x16)_107");
        Sprite ruinAccentSprite = FindSprite(terrainAssets, "Terrain (16x16)_108");
        Sprite spikeSprite = LoadFirstSprite(SpikePath);

        if (goldTopSprite == null || goldFillSprite == null || goldAccentSprite == null ||
            ruinTopSprite == null || ruinFillSprite == null || ruinAccentSprite == null || spikeSprite == null)
        {
            EditorUtility.DisplayDialog("Tile素材が不足しています", "Pixel AdventureのSprite分割・素材名を確認してください。", "OK");
            return false;
        }

        EnsureFolder("Assets/Generated");
        EnsureFolder(GeneratedTileFolder);

        goldTop = LoadOrCreateTile(GeneratedTileFolder + "/GoldTop.asset", goldTopSprite);
        goldFill = LoadOrCreateTile(GeneratedTileFolder + "/GoldFill.asset", goldFillSprite);
        goldAccent = LoadOrCreateTile(GeneratedTileFolder + "/GoldAccent.asset", goldAccentSprite);
        ruinTop = LoadOrCreateTile(GeneratedTileFolder + "/RuinTop.asset", ruinTopSprite);
        ruinFill = LoadOrCreateTile(GeneratedTileFolder + "/RuinFill.asset", ruinFillSprite);
        ruinAccent = LoadOrCreateTile(GeneratedTileFolder + "/RuinAccent.asset", ruinAccentSprite);
        spikeTile = LoadOrCreateTile(GeneratedTileFolder + "/Spikes.asset", spikeSprite);

        cellSize = goldFillSprite.bounds.size.x;
        if (cellSize <= 0.0001f)
            cellSize = 0.16f;

        AssetDatabase.SaveAssets();
        return true;
    }

    private static void BuildTileVisuals(Transform root)
    {
        GameObject gridObject = new GameObject("PixelAdventureGrid");
        gridObject.transform.SetParent(root);
        gridObject.transform.position = new Vector3(0f, 0f, -0.18f);

        Grid grid = gridObject.AddComponent<Grid>();
        grid.cellSize = new Vector3(cellSize, cellSize, 1f);

        Tilemap platformMap = CreateTilemap(gridObject.transform, "GoldPlatforms", -10);
        Tilemap wallMap = CreateTilemap(gridObject.transform, "OrangeWalls", -9);

        foreach (TerrainRect rect in TerrainRects)
            PaintTerrain(rect, rect.isWall ? wallMap : platformMap);
    }

    private static Tilemap CreateTilemap(Transform parent, string name, int order)
    {
        GameObject mapObject = new GameObject(name);
        mapObject.transform.SetParent(parent);

        Tilemap map = mapObject.AddComponent<Tilemap>();
        TilemapRenderer renderer = mapObject.AddComponent<TilemapRenderer>();
        renderer.sortingOrder = order;
        return map;
    }

    private static void PaintTerrain(TerrainRect rect, Tilemap map)
    {
        int width = Mathf.Max(1, Mathf.RoundToInt(rect.size.x / cellSize));
        int height = Mathf.Max(1, Mathf.RoundToInt(rect.size.y / cellSize));
        int minX = Mathf.RoundToInt((rect.center.x - rect.size.x * 0.5f) / cellSize);
        int minY = Mathf.RoundToInt((rect.center.y - rect.size.y * 0.5f) / cellSize);

        for (int y = 0; y < height; y++)
        {
            bool isTop = y == height - 1;
            for (int x = 0; x < width; x++)
            {
                TileBase tile;
                if (rect.isWall)
                {
                    tile = isTop ? ruinTop : ruinFill;
                    if (!isTop && (x + y * 3) % 12 == 0)
                        tile = ruinAccent;
                }
                else
                {
                    tile = isTop ? goldTop : goldFill;
                    if (!isTop && (x + y * 5) % 17 == 0)
                        tile = goldAccent;
                }

                map.SetTile(new Vector3Int(minX + x, minY + y, 0), tile);
            }
        }
    }

