            renderer.color = Color.white;
            renderer.sortingOrder = 6;
        }

        if (collider != null)
        {
            collider.size = new Vector2(0.90f / spriteScale, 1.08f / spriteScale);
            collider.offset = new Vector2(0f, -0.04f / spriteScale);
        }

        int layer = LayerMask.NameToLayer("Enemy");
        if (layer >= 0)
            enemy.layer = layer;
    }

