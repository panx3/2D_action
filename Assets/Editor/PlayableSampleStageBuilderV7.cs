    private static void FitPrefabToWorldSize(GameObject target, Sprite sprite, Vector2 desiredWorldSize, Color tint)
    {
        if (target == null || sprite == null)
            return;

        SpriteRenderer renderer = target.GetComponent<SpriteRenderer>();
        if (renderer == null)
            return;

        BoxCollider2D box = target.GetComponent<BoxCollider2D>();
        Vector2 sourceSize = sprite.bounds.size;
        if (sourceSize.x <= 0.0001f || sourceSize.y <= 0.0001f)
            return;

        target.transform.localScale = new Vector3(desiredWorldSize.x / sourceSize.x, desiredWorldSize.y / sourceSize.y, 1f);

        renderer.sprite = sprite;
        renderer.color = tint;
        renderer.enabled = true;
        renderer.drawMode = SpriteDrawMode.Simple;
        renderer.sortingOrder = 5;

        if (box != null)
        {
            box.size = sourceSize;
            box.offset = Vector2.zero;
        }
    }

    private static void SetBoxColliderWorldSize(GameObject target, Vector2 desiredWorldSize)
    {
        if (target == null)
            return;

        BoxCollider2D box = target.GetComponent<BoxCollider2D>();
        if (box == null)
            return;

        float baseWidth = Mathf.Max(0.0001f, box.size.x * Mathf.Abs(target.transform.localScale.x));
        float baseHeight = Mathf.Max(0.0001f, box.size.y * Mathf.Abs(target.transform.localScale.y));

        target.transform.localScale = new Vector3(
            target.transform.localScale.x * (desiredWorldSize.x / baseWidth),
            target.transform.localScale.y * (desiredWorldSize.y / baseHeight),
            1f);

        box.offset = Vector2.zero;
    }

    private static void ConfigureCircleColliderWorldRadius(CircleCollider2D circle, Transform target, float radius)
    {
        if (circle == null || target == null)
            return;

        float scale = Mathf.Max(0.0001f, Mathf.Abs(target.lossyScale.x));
        circle.radius = radius / scale;
        circle.offset = Vector2.zero;
    }

    private static void CreateCrateStackVisual(Transform parent, Sprite crateSprite, int columns, int rows, Vector2 totalWorldSize)
    {
        if (parent == null || crateSprite == null)
            return;

        Vector2 spriteSize = crateSprite.bounds.size;
        Vector3 parentScale = parent.lossyScale;
        if (spriteSize.x <= 0.0001f || spriteSize.y <= 0.0001f ||
            Mathf.Abs(parentScale.x) <= 0.0001f || Mathf.Abs(parentScale.y) <= 0.0001f)
            return;

        for (int y = 0; y < rows; y++)
        {
            for (int x = 0; x < columns; x++)
            {
                float worldX = ((x + 0.5f) / columns - 0.5f) * totalWorldSize.x;
                float worldY = ((y + 0.5f) / rows - 0.5f) * totalWorldSize.y;

                GameObject crate = new GameObject("CrateVisual");
                crate.transform.SetParent(parent);
                crate.transform.localPosition = new Vector3(worldX / parentScale.x, worldY / parentScale.y, -0.05f);

                float wantedWidth = totalWorldSize.x / columns * 0.90f;
                float wantedHeight = totalWorldSize.y / rows * 0.90f;
                crate.transform.localScale = new Vector3(
                    wantedWidth / spriteSize.x / parentScale.x,
                    wantedHeight / spriteSize.y / parentScale.y,
                    1f);

                SpriteRenderer renderer = crate.AddComponent<SpriteRenderer>();
                renderer.sprite = crateSprite;
                renderer.color = Color.white;
                renderer.sortingOrder = 6;
            }
        }
    }

